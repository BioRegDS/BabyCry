#!/usr/bin/env python3
"""
Figure 2: generalization hierarchy for cry-reason classification.

Dataset
-------
Enes high-confidence Hunger vs Discomfort subset.

Representation
--------------
Variable-duration handcrafted acoustic features generated by:
    src/00_dataset/04_extract_acoustic_features.py

Primary classifier
------------------
LinearSVC with class_weight='balanced'.

Evaluation hierarchy
--------------------
1. Random clip split
2. Session-independent split
3. Infant-independent split
4. Leave-one-infant-out (LOIO)

Outputs
-------
results/02_figure2/
    reason_generalization_summary.csv
    reason_oof_predictions.csv
    loio_infant_auc.csv
"""

from __future__ import annotations

import argparse
from pathlib import Path

import numpy as np
import pandas as pd

from sklearn.impute import SimpleImputer
from sklearn.metrics import (
    balanced_accuracy_score,
    f1_score,
    roc_auc_score,
)
from sklearn.model_selection import (
    LeaveOneGroupOut,
    StratifiedGroupKFold,
    StratifiedKFold,
)
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import StandardScaler
from sklearn.svm import LinearSVC


# ============================================================
# Constants
# ============================================================

META_COLUMNS = {
    "dataset",
    "file",
    "group_id",
    "file_seq_S",
    "baby",
    "sex",
    "age_month",
    "label",
    "original_sr",
    "original_duration_sec",
    "analysis_duration_sec",
}

SEED = 42
N_BOOT = 2000


# ============================================================
# Utilities
# ============================================================

def feature_columns(df):

    return [
        c
        for c in df.columns
        if c not in META_COLUMNS
    ]


def make_model(seed):

    return Pipeline(
        [
            (
                "imputer",
                SimpleImputer(
                    strategy="median",
                ),
            ),
            (
                "scaler",
                StandardScaler(),
            ),
            (
                "model",
                LinearSVC(
                    C=1.0,
                    class_weight="balanced",
                    max_iter=10000,
                    random_state=seed,
                ),
            ),
        ]
    )


def calculate_metrics(
    y,
    score,
):

    pred = (
        score >= 0
    ).astype(int)

    return {
        "auc":
            float(
                roc_auc_score(
                    y,
                    score,
                )
            ),

        "balanced_accuracy":
            float(
                balanced_accuracy_score(
                    y,
                    pred,
                )
            ),

        "f1":
            float(
                f1_score(
                    y,
                    pred,
                    zero_division=0,
                )
            ),
    }


# ============================================================
# OOF prediction
# ============================================================

def oof_predict(
    df,
    features,
    evaluation,
    seed,
):

    y = (
        df["label"]
        == "discomfort"
    ).astype(int).to_numpy()

    score = np.full(
        len(df),
        np.nan,
        dtype=float,
    )

    fold_id = np.full(
        len(df),
        -1,
        dtype=int,
    )

    # --------------------------------------------------------
    # Random clip
    # --------------------------------------------------------

    if evaluation == "random":

        splitter = StratifiedKFold(
            n_splits=5,
            shuffle=True,
            random_state=seed,
        )

        splits = splitter.split(
            df,
            y,
        )

    # --------------------------------------------------------
    # Session-independent
    # --------------------------------------------------------

    elif evaluation == "session":

        splitter = StratifiedGroupKFold(
            n_splits=5,
            shuffle=True,
            random_state=seed,
        )

        splits = splitter.split(
            df,
            y,
            groups=df[
                "file_seq_S"
            ],
        )

    # --------------------------------------------------------
    # Infant-independent 5-fold
    # --------------------------------------------------------

    elif evaluation == "infant":

        splitter = StratifiedGroupKFold(
            n_splits=5,
            shuffle=True,
            random_state=seed,
        )

        splits = splitter.split(
            df,
            y,
            groups=df[
                "baby"
            ],
        )

    # --------------------------------------------------------
    # LOIO
    # --------------------------------------------------------

    elif evaluation == "loio":

        splitter = LeaveOneGroupOut()

        splits = splitter.split(
            df,
            y,
            groups=df[
                "baby"
            ],
        )

    else:

        raise ValueError(
            evaluation
        )

    for fold, (
        train_idx,
        test_idx,
    ) in enumerate(
        splits,
        start=1,
    ):

        model = make_model(
            seed + fold
        )

        model.fit(
            df.iloc[
                train_idx
            ][features],
            y[
                train_idx
            ],
        )

        score[
            test_idx
        ] = (
            model
            .decision_function(
                df.iloc[
                    test_idx
                ][features]
            )
        )

        fold_id[
            test_idx
        ] = fold

    if np.isnan(
        score
    ).any():

        raise RuntimeError(
            f"Missing OOF predictions: "
            f"{evaluation}"
        )

    pred = df[
        [
            "file",
            "file_seq_S",
            "baby",
            "label",
        ]
    ].copy()

    pred[
        "y"
    ] = y

    pred[
        "score"
    ] = score

    pred[
        "fold"
    ] = fold_id

    pred[
        "evaluation"
    ] = evaluation

    return pred


# ============================================================
# Bootstrap confidence intervals
# ============================================================

def bootstrap_auc(
    pred,
    cluster_col,
    n_boot,
    seed,
):

    rng = np.random.default_rng(
        seed
    )

    # clip bootstrap
    if cluster_col is None:

        values = []

        n = len(
            pred
        )

        for _ in range(
            n_boot
        ):

            idx = rng.choice(
                n,
                n,
                replace=True,
            )

            y = pred[
                "y"
            ].to_numpy()[
                idx
            ]

            score = pred[
                "score"
            ].to_numpy()[
                idx
            ]

            if len(
                np.unique(y)
            ) < 2:
                continue

            values.append(
                roc_auc_score(
                    y,
                    score,
                )
            )

    # cluster bootstrap
    else:

        groups = (
            pred[
                cluster_col
            ]
            .astype(str)
            .unique()
        )

        lookup = {
            group:
                pred[
                    pred[
                        cluster_col
                    ].astype(str)
                    == group
                ]
            for group
            in groups
        }

        values = []

        for _ in range(
            n_boot
        ):

            selected = rng.choice(
                groups,
                len(groups),
                replace=True,
            )

            boot = pd.concat(
                [
                    lookup[
                        g
                    ]
                    for g
                    in selected
                ],
                ignore_index=True,
            )

            if (
                boot["y"]
                .nunique()
                < 2
            ):
                continue

            values.append(
                roc_auc_score(
                    boot[
                        "y"
                    ],
                    boot[
                        "score"
                    ],
                )
            )

    values = np.asarray(
        values,
        dtype=float,
    )

    return {
        "bootstrap_mean":
            float(
                np.mean(values)
            ),

        "ci95_low":
            float(
                np.percentile(
                    values,
                    2.5,
                )
            ),

        "ci95_high":
            float(
                np.percentile(
                    values,
                    97.5,
                )
            ),

        "n_boot_valid":
            int(
                len(values)
            ),
    }


# ============================================================
# Infant-wise LOIO
# ============================================================

def infant_auc_table(
    pred,
):

    rows = []

    for baby, g in (
        pred.groupby(
            "baby"
        )
    ):

        if (
            g["y"]
            .nunique()
            < 2
        ):

            auc = np.nan

        else:

            auc = float(
                roc_auc_score(
                    g["y"],
                    g["score"],
                )
            )

        rows.append(
            {
                "baby":
                    baby,

                "n_clips":
                    len(g),

                "n_hunger":
                    int(
                        (
                            g["y"]
                            == 0
                        ).sum()
                    ),

                "n_discomfort":
                    int(
                        (
                            g["y"]
                            == 1
                        ).sum()
                    ),

                "auc":
                    auc,
            }
        )

    return pd.DataFrame(
        rows
    )


# ============================================================
# Main
# ============================================================

def main():

    parser = argparse.ArgumentParser()

    parser.add_argument(
        "--project",
        type=Path,
        default=Path(
            str(Path(__file__).resolve().parents[2])
        ),
    )

    args = parser.parse_args()

    project = (
        args.project
        .resolve()
    )

    input_path = (
        project
        / "data"
        / "processed"
        / "features_variable"
        / "enes_hunger_discomfort.csv"
    )

    outdir = (
        project
        / "results"
        / "02_figure2"
    )

    outdir.mkdir(
        parents=True,
        exist_ok=True,
    )

    df = pd.read_csv(
        input_path
    )

    features = feature_columns(
        df
    )

    print(
        "Rows:",
        len(df)
    )

    print(
        "Features:",
        len(features)
    )

    print(
        "Infants:",
        df[
            "baby"
        ].nunique()
    )

    print(
        "Sessions:",
        df[
            "file_seq_S"
        ].nunique()
    )

    all_predictions = []

    summary_rows = []

    configurations = [
        (
            "random",
            None,
        ),
        (
            "session",
            "file_seq_S",
        ),
        (
            "infant",
            "baby",
        ),
        (
            "loio",
            "baby",
        ),
    ]

    for i, (
        evaluation,
        bootstrap_cluster,
    ) in enumerate(
        configurations
    ):

        print(
            "\nRunning:",
            evaluation,
            flush=True,
        )

        pred = oof_predict(
            df,
            features,
            evaluation,
            SEED,
        )

        metrics = calculate_metrics(
            pred[
                "y"
            ].to_numpy(),
            pred[
                "score"
            ].to_numpy(),
        )

        ci = bootstrap_auc(
            pred,
            bootstrap_cluster,
            N_BOOT,
            SEED
            + 100
            + i,
        )

        summary_rows.append(
            {
                "evaluation":
                    evaluation,

                **metrics,
                **ci,
            }
        )

        all_predictions.append(
            pred
        )

        print(
            {
                **metrics,
                **ci,
            }
        )

    summary = pd.DataFrame(
        summary_rows
    )

    predictions = pd.concat(
        all_predictions,
        ignore_index=True,
    )

    loio_pred = predictions[
        predictions[
            "evaluation"
        ]
        == "loio"
    ].copy()

    infant_auc = infant_auc_table(
        loio_pred
    )

    summary.to_csv(
        outdir
        / "reason_generalization_summary.csv",
        index=False,
    )

    predictions.to_csv(
        outdir
        / "reason_oof_predictions.csv",
        index=False,
    )

    infant_auc.to_csv(
        outdir
        / "loio_infant_auc.csv",
        index=False,
    )

    print(
        "\n===== REASON GENERALIZATION ====="
    )

    print(
        summary.to_string(
            index=False
        )
    )

    valid = (
        infant_auc[
            "auc"
        ]
        .dropna()
    )

    print(
        "\n===== LOIO INFANT AUC ====="
    )

    print(
        "AUC defined:",
        len(valid),
        "/",
        len(
            infant_auc
        )
    )

    print(
        "Median:",
        valid.median()
    )

    print(
        "Mean:",
        valid.mean()
    )


if __name__ == "__main__":
    main()
